"""Write the dashboard out in another language.

Everything a card draws is translated by the cards themselves, and every entity
name by Home Assistant. What is left is the dashboard's own text -- section
headings, chart titles, the names given to chart series -- which is literal text
in the YAML and belongs to no entity, so nothing else can translate it.

Rather than keep a second copy of a 300-line dashboard in step by hand, this
walks the English one and swaps those literals for their translations. A phrase
with no translation is an error naming the phrase, not a silent copy: the
failure this exists to prevent is a dashboard that is Ukrainian except for the
two headings somebody added last week.

Comments do not survive a YAML round trip, which is why the English file stays
the one to read and edit -- it carries the reasoning, and this output carries a
header saying so.

    python3 tools/localise_dashboard.py           # write dashboards/futura.uk.yaml
    python3 tools/localise_dashboard.py --check    # fail if it is out of date
"""

from __future__ import annotations

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "dashboards" / "futura.yaml"

#: The keys whose values are text a person reads. `entity`, `path`, `icon` and
#: the rest are identifiers and must not be touched.
TRANSLATED_KEYS = ("title", "heading", "name")

#: English phrase -> language -> translation. `Futura` is the product's name and
#: is deliberately mapped to itself: it is listed so the "every phrase is
#: accounted for" check stays honest rather than carrying an exception list.
PHRASES: dict[str, dict[str, str]] = {
    "Futura": {"uk": "Futura"},
    "Unit": {"uk": "Установка"},
    "Settings": {"uk": "Налаштування"},
    "Active faults": {"uk": "Активні несправності"},
    "Active warnings": {"uk": "Активні попередження"},
    "Air quality": {"uk": "Якість повітря"},
    "Trends": {"uk": "Тренди"},
    "Air temperature": {"uk": "Температура повітря"},
    "Air humidity": {"uk": "Вологість повітря"},
    "Power and recovery": {"uk": "Потужність і рекуперація"},
    "Fan output": {"uk": "Потужність вентиляторів"},
    "Air flow": {"uk": "Витрата повітря"},
    # Chart series. Short on purpose: these sit in a legend under the plot, and
    # the four ducts are told apart by one word each.
    "Outside": {"uk": "Зовнішнє"},
    "Supply": {"uk": "Припливне"},
    "Inside": {"uk": "Витяжне"},
    "Waste": {"uk": "Викидне"},
    "Outdoor probe": {"uk": "Зовні (NTC)"},
    "Power": {"uk": "Потужність"},
    "Recovered": {"uk": "Рекуперовано"},
    "Supply %": {"uk": "Приплив %"},
    "Exhaust %": {"uk": "Витяжка %"},
}

LANGUAGES = sorted({lang for phrase in PHRASES.values() for lang in phrase})

HEADER = """\
# Jablotron Futura dashboard -- {language}
#
# Generated by tools/localise_dashboard.py from dashboards/futura.yaml. Edit
# that file, or tools/localise_dashboard.py for the wording, and run the tool
# again; the comments explaining each choice live there.
"""


def translate(node: object, language: str, missing: list[str]) -> object:
    """A copy of `node` with every readable string translated."""
    if isinstance(node, dict):
        out = {}
        for key, value in node.items():
            if key in TRANSLATED_KEYS and isinstance(value, str):
                known = PHRASES.get(value, {})
                if language in known:
                    out[key] = known[language]
                else:
                    missing.append(value)
                    out[key] = value
            else:
                out[key] = translate(value, language, missing)
        return out
    if isinstance(node, list):
        return [translate(item, language, missing) for item in node]
    return node


def render(language: str) -> tuple[str, list[str]]:
    missing: list[str] = []
    translated = translate(yaml.safe_load(SOURCE.read_text()), language, missing)
    body = yaml.safe_dump(
        translated, allow_unicode=True, sort_keys=False, width=100, indent=2
    )
    return HEADER.format(language=language) + body, sorted(set(missing))


def main(argv: list[str]) -> int:
    check = "--check" in argv
    status = 0
    for language in LANGUAGES:
        path = SOURCE.with_suffix(f".{language}.yaml")
        text, missing = render(language)
        if missing:
            print(f"{language}: no translation for {missing}", file=sys.stderr)
            status = 1
            continue
        current = path.read_text() if path.exists() else None
        if current == text:
            print(f"{path.name}: current")
        elif check:
            print(f"{path.name}: out of date", file=sys.stderr)
            status = 1
        else:
            path.write_text(text)
            print(f"{path.name}: written")
    return status


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
